#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Bake deploy/apps/lang/*.lang into a compiled-in fallback table.

Boards that can reach the Lua Store download their language as a file. Boards
that cannot (the V4: ~14 KB of free internal heap, so the net worker and the
store are unreliable there) still need translations, and before this they were
stuck on English.

This generates src/ui-touch/i18n_builtin.h from the SAME .lang files the store
serves, so the two can never drift: translators edit deploy/apps/lang/*.lang,
and both paths follow. Rows are emitted sorted by key so TR() can binary-search
them, and the table lives in .rodata — flash, not RAM.

Run from the repo root (a PlatformIO pre-build step does this automatically):
    python3 scripts/build/gen-lang-builtin.py
"""
import zlib, glob, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lang_reach   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LANGDIR = os.path.join(ROOT, 'deploy/apps/lang')
OUT = os.path.join(ROOT, 'src/ui-touch/i18n_builtin.h')

# The baked table used to be pinned to a frozen copy of the .lang files: beta_93 pushed
# the Heltec V4 5.6 KB over its flash, so it kept the beta_92 table (lang-pin-beta92/).
# Since beta_94 it bakes the live files again, but only the keys some source can look up
# (lang_reach.py): that table is ~16 KB SMALLER than the pinned one was. To pin again, set
# PIN_DIR to a directory of .lang files (the beta_92 copy is in git history).
PIN_DIR = None

# Index order must match the UiLang enum in i18n.h.
CODES = ["en", "hu", "nl", "de", "fr", "es", "it",
         "ru", "uk", "bg", "sr", "el", "pt-br", "ro", "cs"]


def c_escape(s):
    out = []
    for ch in s:
        if ch == '\\':   out.append('\\\\')
        elif ch == '"':  out.append('\\"')
        elif ch == '\n': out.append('\\n')
        elif ch == '\t': out.append('\\t')
        elif ch == '\r': out.append('\\r')
        elif ord(ch) < 0x20: out.append('\\x%02x' % ord(ch))
        else: out.append(ch)
    return ''.join(out)


def read_lang(path):
    """key -> value, with the file's own \\n/\\t/\\\\ escapes decoded."""
    rows = {}
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n').rstrip('\r')
        if '\t' not in line:          # header/comment lines carry no tab
            continue
        k, v = line.split('\t', 1)
        def un(t):
            o, i = [], 0
            while i < len(t):
                if t[i] == '\\' and i + 1 < len(t):
                    n = t[i + 1]
                    o.append('\n' if n == 'n' else '\t' if n == 't' else n)
                    i += 2
                else:
                    o.append(t[i]); i += 1
            return ''.join(o)
        k, v = un(k), un(v)
        if k and v:
            rows[k] = v
    return rows


def load_langs():
    langs = {}
    src_dir = PIN_DIR or LANGDIR
    for code in CODES[1:]:                      # English is the key itself
        p = os.path.join(src_dir, code + '.lang')
        if os.path.exists(p):
            langs[code] = read_lang(p)
    if not langs:
        sys.exit('no .lang files found in ' + src_dir)
    return langs


def check_objects(build_dir):
    """Guard for the V4 build (run after linking): every translated key the compiler
    emitted into the V4's objects must be in the baked table."""
    langs = load_langs()
    allkeys = set().union(*[set(r) for r in langs.values()])
    keep = lang_reach.reachable_keys(ROOT, allkeys)
    miss = lang_reach.oracle_missing(build_dir, allkeys, keep)
    if miss:
        print('i18n: %d key(s) in the V4 objects were trimmed from i18n_builtin.h:' % len(miss))
        for k in miss[:40]:
            print('   ', repr(k))
        sys.exit(1)
    print('i18n: built-in table covers every translated key in the build')


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--check-objects':
        return check_objects(sys.argv[2])
    langs = load_langs()
    allkeys = set().union(*[set(r) for r in langs.values()])
    try:
        keep = lang_reach.reachable_keys(ROOT, allkeys)
    except RuntimeError as e:
        # Never trim blind, and never fail a build over it: boards other than the V4 do
        # not even compile the table. The V4's post-link check catches a stale one.
        print('i18n: cannot work out the reachable keys (%s); i18n_builtin.h left as it is' % e)
        return

    # Each language is ONE raw-deflated blob of its sorted "key\0value\0" rows. The
    # V4 inflates the active language into PSRAM on first use (i18n.cpp) and binary-
    # searches it there. The plain table was ~694 KB of the V4's flash (2026-10-15,
    # the 1.18 core left 1.5 KB free); deflated it is roughly a third of that.
    w = ['// Generated by scripts/build/gen-lang-builtin.py — DO NOT EDIT.',
         '// Source: deploy/apps/lang/*.lang (the same files the Lua Store serves).',
         '// Compiled-in fallback for boards that cannot rely on downloading a language:',
         '// one raw-deflated blob of sorted "key\\0value\\0" rows per language (i18n.cpp).',
         '#pragma once', '#include <stdint.h>', '#include "i18n.h"', '',
         'struct I18nBlob { const uint8_t* z; uint32_t zlen; uint32_t len; uint16_t count; };', '']
    blobs = {}
    for code in CODES[1:]:
        rows = langs.get(code, {})
        # A row whose translation IS the key does nothing: TR() already returns the
        # key when it finds no match. The .lang files carry those deliberately, as
        # placeholders telling translators the string exists, but baking them costs
        # flash on exactly the board that needs the flash.
        keys = [k for k in sorted(rows, key=lambda x: x.encode('utf-8'))   # TR() strcmp-searches
                if rows[k] != k and k in keep]
        if not keys:
            continue
        raw = b''.join(k.encode('utf-8') + b'\0' + rows[k].encode('utf-8') + b'\0' for k in keys)
        c = zlib.compressobj(9, zlib.DEFLATED, -15)
        z = c.compress(raw) + c.flush()
        sym = 'kI18nZ_' + code.replace('-', '_')
        blobs[code] = (sym, len(z), len(raw), len(keys))
        w.append('static const uint8_t %s[%d] = {  // %d rows, %d B' % (sym, len(z), len(keys), len(raw)))
        for i in range(0, len(z), 24):
            w.append('  ' + ','.join('0x%02x' % x for x in z[i:i + 24]) + ',')
        w.append('};')
    w.append('')
    w.append('static const I18nBlob kBuiltinBlob[LANG_COUNT] = {')
    w.append('  { nullptr, 0, 0, 0 },')                       # LANG_EN: the key is the English
    for code in CODES[1:]:
        if code in blobs:
            sym, zl, rl, n = blobs[code]
            w.append('  { %s, %d, %d, %d },' % (sym, zl, rl, n))
        else:
            w.append('  { nullptr, 0, 0, 0 },')
    w.append('};')
    w.append('')

    text = '\n'.join(w)
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if text != old:
        open(OUT, 'w', encoding='utf-8').write(text)
    else:
        os.utime(OUT)   # unchanged: mark it current so the pre-build check stops asking
    total = sum(sum(1 for k, v in r.items() if v != k and k in keep) for r in langs.values())
    print('%s: %d languages, %d translated rows (%d of %d keys reachable), %d B deflated from %d B%s' %
          (os.path.relpath(OUT, ROOT), len(langs), total, len(keep), len(allkeys),
           sum(b[1] for b in blobs.values()), sum(b[2] for b in blobs.values()),
           '' if text != old else ', unchanged'))


if __name__ == '__main__':
    main()
