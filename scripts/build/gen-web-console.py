#!/usr/bin/env python3
"""Pack web/console/*.html into src/helpers/esp32/WebConsoleAssets.h (gzip, served as-is).

Each page may pull in a shared snippet with <!--#include name--> or /*#include name*/.
The gzip header carries no name or timestamp, so the output only changes with the
sources. The header is committed: the ESP-IDF builds do not run PlatformIO hooks.
"""
import gzip, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "web", "console")
OUT = os.path.join(ROOT, "src", "helpers", "esp32", "WebConsoleAssets.h")
PAGES = [("index", "WC_INDEX"), ("mesh", "WC_MESH"), ("screen", "WC_SCREEN"), ("files", "WC_FILES")]
INC = re.compile(r"<!--#include ([\w.]+)-->|/\*#include ([\w.]+)\*/")


def expand(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        text = f.read()
    return INC.sub(lambda m: expand(m.group(1) or m.group(2)).rstrip("\n"), text)


def render():
    out = ["// SPDX-License-Identifier: GPL-3.0-or-later",
           "// GENERATED by scripts/build/gen-web-console.py from web/console/ - do not edit.",
           "#pragma once", "#include <stddef.h>", "#include <stdint.h>", ""]
    for page, sym in PAGES:
        raw = expand(page + ".html").encode("utf-8")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        out.append("// %s.html: %d bytes, %d gzipped" % (page, len(raw), len(gz)))
        out.append("static const uint8_t %s_GZ[] = {" % sym)
        for i in range(0, len(gz), 20):
            out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
        out.append("};")
        out.append("static const size_t %s_GZ_LEN = sizeof(%s_GZ);" % (sym, sym))
        out.append("")
    return "\n".join(out)


def main():
    text = render()
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in sys.argv:
        if old != text:
            print("WebConsoleAssets.h is stale: run scripts/build/gen-web-console.py")
            return 1
        return 0
    if old != text:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print("web console: wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
