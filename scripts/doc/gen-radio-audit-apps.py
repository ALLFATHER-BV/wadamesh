#!/usr/bin/env python3
"""Embed the RF Monitor and Airtime sources for the DOC_RADIO_AUDIT capture build.

    python3 scripts/doc/gen-radio-audit-apps.py
    PLATFORMIO_BUILD_FLAGS="-DDOC_CAPTURE -DDOC_AUDIT_FOCUS -DDOC_RADIO_AUDIT" pio run -e <env> -t upload
    python3 scripts/doc/capture.py <port> doc-shots

Writes src/ui-touch/doc_radio_apps.h (gitignored) from the versions apps.json lists,
so the shots show deploy/apps as it is now rather than what the Store serves.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
cat = {a['id']: a['ver'] for a in json.load(open(os.path.join(ROOT, 'deploy/apps/apps.json')))['apps']}
def src(aid):
    return open(os.path.join(ROOT, 'deploy/apps', aid, cat[aid], aid + '.lua'), encoding='utf-8').read()
out = os.path.join(ROOT, 'src/ui-touch/doc_radio_apps.h')
open(out, 'w', encoding='utf-8').write(
    '// GENERATED by scripts/doc/gen-radio-audit-apps.py for the DOC_RADIO_AUDIT build. Not committed.\n'
    '#pragma once\n'
    'static const char kAuditMonitor[] = R"WADALUA(' + src('monitor') + ')WADALUA";\n'
    'static const char kAuditAirtime[] = R"WADALUA(' + src('airtime') + ')WADALUA";\n'
    'static const char kAuditMusic[] = R"WADALUA(' + src('music') + ')WADALUA";\n')
# Every catalog app, for the Store page screenshots (DOC_APPS_AUDIT).
apps = json.load(open(os.path.join(ROOT, 'deploy/apps/apps.json')))['apps']
rows = []
with open(out, 'a', encoding='utf-8') as f:
    for i, a in enumerate(apps):
        code = src(a['id'])
        assert ')WADALUA"' not in code, a['id']
        f.write('static const char kAuditStoreSrc%d[] = R"WADALUA(%s)WADALUA";\n' % (i, code))
        rows.append('  { "%s", "%s", kAuditStoreSrc%d },' % (a['id'], a['name'], i))
    f.write('struct AuditStoreApp { const char* id; const char* name; const char* src; };\n')
    f.write('static const AuditStoreApp kAuditStore[] = {\n' + '\n'.join(rows) + '\n};\n')
    f.write('static const int kAuditStoreCount = %d;\n' % len(rows))
print('wrote', os.path.relpath(out, ROOT), 'monitor', cat['monitor'], 'airtime', cat['airtime'], 'music', cat['music'], '+', len(rows), 'store apps')
