# Generates zero_font.h: a 7x13 bitmap terminal font (ASCII 32..126) from DejaVu Sans Mono,
# with 4-level antialiasing (2 bits per pixel) so it stays readable on the 1.9" LCD.
import sys
from PIL import Image, ImageDraw, ImageFont
CW,CH=7,13
f=ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',11)
out=[]
for c in range(32,127):
    im=Image.new('L',(CW,CH),0); d=ImageDraw.Draw(im)
    d.text((0,-1),chr(c),font=f,fill=255)
    px=list(im.tobytes())
    out.append([min(3,(v+42)//85) for v in px])
with open(sys.argv[1],'w') as o:
    o.write('// generated by gen_font.py: 7x13 terminal font, ASCII 32..126, 2 bits/pixel\n#pragma once\n#include <stdint.h>\n')
    o.write(f'static const int kTermCW={CW}, kTermCH={CH};\nstatic const uint8_t kTermFont[95][{CW*CH}]={{\n')
    for g in out: o.write('{'+','.join(map(str,g))+'},\n')
    o.write('};\n')
