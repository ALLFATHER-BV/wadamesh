# Renders the Cardputer Zero key-help overlay (fn + H) to zero_help.h (RGB565, 320x170).
import sys
from PIL import Image, ImageDraw, ImageFont
W,H=320,170
F='/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed.ttf'
FB='/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf'
f=ImageFont.truetype(F,11); fb=ImageFont.truetype(FB,11); ft=ImageFont.truetype(FB,12)
im=Image.new('RGB',(W,H),(10,22,24)); d=ImageDraw.Draw(im)
d.text((6,3),'WADAMESH keys',font=ft,fill=(25,220,200))
d.text((W-6,4),'any key closes',font=f,fill=(120,150,150),anchor='ra')
d.line((6,19,W-6,19),fill=(40,70,70))
rows=[
 ('F / X','up / down','Z / C','left / right'),
 ('OK','select / send','ESC','back (hold: Home)'),
 ('1','system HUD','2','Linux shell'),
 ('fn+FZXC','arrows (typing)','fn+J','screenshot'),
 ('fn+U / I','brightness','fn+H','this help'),
 ('Ctrl+Q','quit','ssh','wadamesh-cli'),
]
y=24
for a,b,c,e in rows:
    d.text((6,y),a,font=fb,fill=(255,200,60)); d.text((70,y),b,font=f,fill=(225,235,235))
    d.text((166,y),c,font=fb,fill=(255,200,60)); d.text((214,y),e,font=f,fill=(225,235,235))
    y+=16
d.text((6,y+1),'letters, 1, 2, 4-8 type normally in a text field',font=f,fill=(120,150,150))
# the five keys under the screen: 4 5 6 7 8 at x = 49 105 161 217 273 (cardputer.cc guide)
tabs=[('4','Msgs'),('5','Contacts'),('6','Home'),('7','Map'),('8','Settings')]
for (k,t),x in zip(tabs,[49,105,161,217,273]):
    d.rounded_rectangle((x-25,140,x+25,166),radius=5,fill=(28,48,50))
    d.text((x,142),k,font=fb,fill=(255,200,60),anchor='ma'); d.text((x,154),t,font=f,fill=(225,235,235),anchor='ma')
    d.line((x,166,x,169),fill=(25,220,200))
if len(sys.argv)>2: im.resize((W*2,H*2),Image.NEAREST).save(sys.argv[2])
px=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b in im.get_flattened_data()]
with open(sys.argv[1],'w') as o:
    o.write('// generated by gen_help.py\n#pragma once\n#include <stdint.h>\nstatic const int kZeroHelpW=320,kZeroHelpH=170;\nstatic const uint16_t kZeroHelp[]={\n')
    for i in range(0,len(px),16): o.write(','.join('0x%04x'%v for v in px[i:i+16])+',\n')
    o.write('};\n')
